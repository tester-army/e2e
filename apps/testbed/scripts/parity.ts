/**
 * Runs the parity suite (e2e.parity.config.ts) and holds its result to
 * tests-parity/expected-gaps.txt: a failure the file does not list, a listed
 * gap that passes or no longer runs, and a `TODO` reason all fail. Extra
 * arguments go to `e2e run`. `E2E_PARITY_UPDATE=1` rewrites the file instead.
 */

import { spawnSync } from 'node:child_process';
import { existsSync, readFileSync } from 'node:fs';
import path from 'node:path';
import { diffGaps, readGaps, writeGaps, type ParityResult } from './parity-gaps.ts';

const root = path.join(import.meta.dirname, '..');
const output = path.join(root, '.e2e-parity');
const gapsFile = path.join(root, 'tests-parity/expected-gaps.txt');
const HEADER = [
  '# Playwright tests e2e fails on purpose or by a known gap, one per line:',
  '# file > describe > test [target] | reason',
  '# Generated by E2E_PARITY_UPDATE=1; edit only the reasons. See scripts/parity-gaps.ts.',
].join('\n');

const run = spawnSync(
  process.execPath,
  ['node_modules/e2e/dist/cli/bin.js', 'run', '--config', 'e2e.parity.config.ts', '--output', output, ...process.argv.slice(2)],
  { cwd: root, stdio: 'inherit' },
);
// 1 is a failed test and 3 an infrastructure failure, either of which can be a listed gap.
const reportFile = path.join(output, 'report.json');
if (![0, 1, 3].includes(run.status ?? -1) || !existsSync(reportFile)) {
  console.error(`parity: e2e run exited ${run.status ?? run.signal} without a report to check`);
  process.exit(1);
}
const results = (JSON.parse(readFileSync(reportFile, 'utf8')) as { run: { results: ParityResult[] } }).run.results;
const gaps = readGaps(gapsFile);

if (process.env['E2E_PARITY_UPDATE'] === '1') {
  writeGaps(gapsFile, HEADER, gaps, results);
  console.log(`parity: rewrote ${path.relative(root, gapsFile)}`);
  process.exit(0);
}

const diff = diffGaps(gaps, results);
const groups = [
  ['failed, and not listed in expected-gaps.txt', diff.unexpected],
  ['gap closed: passes now, delete its line', diff.closed],
  ['listed, but skipped or gone: delete or rename its line', diff.stale],
  ['listed without a reason', diff.todo],
] as const;
let failed = false;
for (const [title, keys] of groups) {
  if (keys.length === 0) continue;
  failed = true;
  console.error(`\nparity: ${title} (${keys.length}):`);
  for (const key of keys) console.error(`  ${key}`);
}
if (failed) {
  console.error('\nparity: E2E_PARITY_UPDATE=1 rewrites the file from this run');
  process.exit(1);
}
console.log(`\nparity: every failure is a listed gap (${gaps.size} listed)`);
